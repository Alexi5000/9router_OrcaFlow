function maskApiKey(key) {
  if (!key || typeof key !== "string") return null;
  const trimmed = key.trim();
  if (trimmed.length <= 12) return trimmed.charAt(0) + "***";
  // Keep the tail: keys sharing a machine-id prefix (team keys) must not collide.
  return trimmed.slice(0, 8) + "***" + trimmed.slice(-4);
}

const KILO_HOURLY_REQUEST_LIMIT = 200;
const pendingRequestEntries = global._pendingRequestEntries ||= {};

function buildPendingRequestEntryKey(connectionId, provider, model, requestId = null) {
  if (requestId) return requestId;
  return `${connectionId || "local"}:${provider || "unknown"}:${model || "unknown"}`;
}

function normalizePendingRoute(route, provider, model, requestedModel = null) {
  return normalizeRequestRoute(route, {
    requestedModel: requestedModel || route?.requestedModel || model,
    resolvedProvider: provider,
    resolvedModel: model,
    finalModel: provider && model ? `${provider}/${model}` : null,
  });
}

function getLivePendingRequests(connectionMap = {}) {
  return Object.values(pendingRequestEntries)
    .filter((entry) => entry && entry.provider && entry.model)
    .sort((a, b) => new Date(b.timestamp || 0) - new Date(a.timestamp || 0))
    .map((entry) => ({
      requestId: entry.requestId,
      timestamp: entry.timestamp,
      model: entry.model,
      provider: entry.provider,
      account: entry.connectionId
        ? (connectionMap[entry.connectionId] || `Account ${entry.connectionId.slice(0, 8)}...`)
        : "Local",
      count: entry.count || 1,
      status: "pending",
      promptTokens: 0,
      completionTokens: 0,
      route: entry.route || null,
      routeSummary: entry.routeSummary || buildRequestRouteSummary(entry.route),
      endpoint: entry.endpoint || null,
    }));
}

function buildHistoryRecentRequests(history = []) {
  const seen = new Set();
  return [...history]
    .sort((a, b) => new Date(b.timestamp) - new Date(a.timestamp))
    .map((e) => {
      const t = e.tokens || {};
      const promptTokens = t.prompt_tokens || t.input_tokens || 0;
      const completionTokens = t.completion_tokens || t.output_tokens || 0;
      const route = normalizeRequestRoute(e.route, {
        requestedModel: e.model,
        resolvedProvider: e.provider,
        resolvedModel: e.model,
        finalModel: e.provider && e.model ? `${e.provider}/${e.model}` : null,
      });
      return {
        timestamp: e.timestamp,
        model: e.model,
        provider: e.provider || "",
        promptTokens,
        completionTokens,
        status: e.status || "ok",
        route,
        routeSummary: buildRequestRouteSummary(route),
      };
    })
    .filter((e) => {
      if (e.promptTokens === 0 && e.completionTokens === 0) return false;
      const minute = e.timestamp ? e.timestamp.slice(0, 16) : "";
      const key = `${e.model}|${e.provider}|${e.promptTokens}|${e.completionTokens}|${minute}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
}

function mergeRecentRequests(liveRequests = [], historyRequests = [], limit = 20) {
  const merged = [];
  const seen = new Set();

  for (const entry of [...liveRequests, ...historyRequests]) {
    const key = entry.requestId || `${entry.timestamp || ""}|${entry.provider || ""}|${entry.model || ""}|${entry.status || ""}`;
    if (seen.has(key)) continue;
    seen.add(key);
    merged.push(entry);
    if (merged.length >= limit) break;
  }

  return merged;
}

function getHourWindowStart(now = Date.now()) {
  const hourStart = new Date(now);
  hourStart.setMinutes(0, 0, 0);
  return hourStart.getTime();
}

function buildKiloHourlyStats(history, kiloConnections = [], now = Date.now()) {
  const hourStart = getHourWindowStart(now);
  const resetInMs = getMsUntilNextHour(now);
  const resetAt = new Date(now + resetInMs).toISOString();
  const seen = new Set();
  const requests = [];

  for (const entry of history || []) {
    if (entry?.provider !== "kilocode" || !isKilocodeHourlyFreeModel(entry?.model)) {
      continue;
    }

    const entryTime = new Date(entry.timestamp).getTime();
    if (!Number.isFinite(entryTime) || entryTime < hourStart || entryTime > now) {
      continue;
    }

    const { promptTokens, completionTokens } = getTokenCounts(entry.tokens);
    const minute = entry.timestamp ? entry.timestamp.slice(0, 16) : "";
    const dedupeKey = [
      entry.provider,
      entry.model,
      promptTokens,
      completionTokens,
      minute,
    ].join("|");

    if (seen.has(dedupeKey)) continue;
    seen.add(dedupeKey);

    requests.push({
      model: entry.model,
      timestamp: entry.timestamp,
      promptTokens,
      completionTokens,
    });
  }

  const byModel = {};
  for (const request of requests) {
    if (!byModel[request.model]) {
      byModel[request.model] = { requests: 0, lastUsed: request.timestamp };
    }
    byModel[request.model].requests += 1;
    if (request.timestamp > byModel[request.model].lastUsed) {
      byModel[request.model].lastUsed = request.timestamp;
    }
  }

  const requestsThisHour = requests.length;
  const remainingRequests = Math.max(KILO_HOURLY_REQUEST_LIMIT - requestsThisHour, 0);
  const usedPercent = Math.min((requestsThisHour / KILO_HOURLY_REQUEST_LIMIT) * 100, 100);
  const burstStatus = getKiloBurstStatus(kiloConnections, now);
  const kiloConnection = kiloConnections.find((connection) => connection.provider === "kilocode" && connection.isActive !== false) || null;
  const effectiveStatus = kiloConnection ? getEffectiveConnectionStatus(kiloConnection, now) : null;
  const connectionUnavailable = effectiveStatus === "unavailable" && isGlobalProviderHealthError(kiloConnection?.errorCode, kiloConnection?.lastError || "");

  let state = "available";
  let statusText = `${remainingRequests} free requests left this hour.`;

  if (!burstStatus.configured) {
    state = "unconfigured";
    statusText = "Kilo is not configured.";
  } else if (burstStatus.parked) {
    state = "parked";
    statusText = `Kilo burst is parked until ${burstStatus.resetAt || resetAt}.`;
  } else if (connectionUnavailable) {
    state = "unavailable";
    statusText = kiloConnection?.lastError
      ? `Kilo is temporarily unavailable: ${kiloConnection.lastError}`
      : "Kilo is temporarily unavailable.";
  } else if (burstStatus.degraded) {
    state = "degraded";
    statusText = `${burstStatus.availableModels.length} Kilo burst lane is live, ${burstStatus.lockedModels.length} parked.`;
  }

  return {
    requestLimit: KILO_HOURLY_REQUEST_LIMIT,
    requestsThisHour,
    remainingRequests,
    usedPercent,
    resetAt,
    resetInMs,
    byModel,
    state,
    statusText,
    connectionStatus: effectiveStatus || kiloConnection?.testStatus || null,
    lastError: kiloConnection?.lastError || null,
    lastErrorAt: kiloConnection?.lastErrorAt || null,
    burst: burstStatus,
  };
}

function getTokenCounts(tokens = {}) {
  return {
    promptTokens: tokens.prompt_tokens || tokens.input_tokens || 0,
    completionTokens: tokens.completion_tokens || tokens.output_tokens || 0,
  };
}

